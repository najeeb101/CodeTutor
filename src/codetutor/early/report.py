"""The early-warning report (Week 8 Step 3a): Markdown, the same input gives the same bytes.

Numbers are formatted with `fixed` (round half up). The reading of the numbers is computed from
them, so the text cannot say something the tables do not.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from codetutor.early.evaluate import (
    AT_RISK_BELOW,
    MAIN_CUTOFF,
    TOP_K,
    Experiment,
    MethodScore,
)
from codetutor.early.features import FEATURE_NAMES
from codetutor.early.logistic import LogisticModel
from codetutor.evals.report import fixed

MODEL = "Logistic model"
BASELINE = "Low first-try share"


@dataclass(frozen=True)
class EarlyClass:
    """One scored class: its facts and one Experiment per cutoff (fitted on the training class)."""

    seed: int
    database: str
    submissions: int
    students: int
    experiments: Mapping[int, Experiment]  # cutoff -> result
    stopped: int  # students who stopped coming before the class's last week
    stopped_flagged: int  # of those, how many are in the main model's top TOP_K


def render_report(
    classes: Sequence[EarlyClass], models: Mapping[int, LogisticModel], train_seed: int
) -> str:
    """The whole report. `classes` are scored with models fitted on class `train_seed`."""
    held_out = [c for c in classes if c.seed != train_seed]
    parts = [
        _intro(train_seed),
        _classes_section(classes),
        _results_section(classes, train_seed),
        _early_section(held_out),
        _weights_section(models[MAIN_CUTOFF]),
        _stopped_section(classes),
        _reading_section(held_out),
        _limits_section(classes, held_out),
    ]
    return "\n\n".join(parts) + "\n"


def _intro(train_seed: int) -> str:
    return f"""# Early warning: who may struggle later? (Week 8 Step 3a)

Generated by `scripts/early_warning.py report` (`make early`). Do not edit by hand.

**The question.** At the end of week {MAIN_CUTOFF}, which students will solve fewer than
{fixed(100 * AT_RISK_BELOW, 0)}% of the problems they first try *after* that week on the first
try? That share is the label. It is read from the submissions table (outcomes), never from the
simulator's persona labels. The cutoff and the {fixed(100 * AT_RISK_BELOW, 0)}% were fixed
before any result was seen.

**Inputs.** Only submissions made up to the cutoff (a test pins that later rows cannot leak
in): first-try share, problems tried, tries per solved problem, activity trend, days since the
last submission, and a Rasch skill fitted on the first tries so far.

**Model.** Logistic regression in pure Python, standardised inputs, a fixed L2 penalty of 1.0.
It is fitted on class seed {train_seed} and scored on the other class. Nothing was tuned on the
class it is scored on. Two simple rules are scored beside it, because a model only matters if
it beats them. A teacher looks at the top {TOP_K} students, so precision and recall are for
those {TOP_K} (no probability threshold to tune)."""


def _classes_section(classes: Sequence[EarlyClass]) -> str:
    rows = []
    for c in classes:
        e = c.experiments[MAIN_CUTOFF]
        rows.append(
            [
                str(c.seed),
                f"`{c.database}`",
                str(c.students),
                str(c.submissions),
                str(e.scored),
                f"{e.positives} ({fixed(100 * e.base_rate, 0)}%)",
                f"{e.no_label} / {e.not_started}",
            ]
        )
    table = _table(
        [
            "seed",
            "database",
            "students",
            "submissions",
            f"scored (week {MAIN_CUTOFF})",
            "at risk",
            "no label / not started",
        ],
        rows,
    )
    return (
        "## The classes\n\n"
        + table
        + "\n\n*no label*: active by the cutoff but with no graded first try after it, so there "
        "is nothing to predict. *not started*: a label but no submission by the cutoff."
    )


def _method_rows(methods: Sequence[MethodScore], base_rate: float) -> list[list[str]]:
    rows = [
        [
            m.name,
            f"{fixed(m.auc, 2)} [{fixed(m.low, 2)}, {fixed(m.high, 2)}]",
            fixed(m.precision, 2),
            fixed(m.recall, 2),
        ]
        for m in methods
    ]
    rows.append(["Random order", "0.50", fixed(base_rate, 2), "–"])
    return rows


def _results_section(classes: Sequence[EarlyClass], train_seed: int) -> str:
    header = [
        "Method",
        "AUC [95% over students]",
        f"Precision, top {TOP_K}",
        f"Recall, top {TOP_K}",
    ]
    parts = [f"## Results at the end of week {MAIN_CUTOFF}"]
    for c in sorted(classes, key=lambda c: c.seed == train_seed):
        e = c.experiments[MAIN_CUTOFF]
        kind = (
            "the class the model was fitted on (not a fair test)"
            if c.seed == train_seed
            else ("held out: the number to quote")
        )
        parts.append(
            f"### Seed {c.seed}: {kind}\n\n"
            + _table(header, _method_rows(e.methods, e.base_rate))
            + f"\n\nAUC: the chance that a random at-risk student scores higher than a random "
            f"other student (0.50 = chance, 1.00 = perfect). Recall is capped at "
            f"{fixed(min(1.0, TOP_K / e.positives), 2)} because only {TOP_K} students are "
            f"flagged and {e.positives} are at risk."
        )
    return "\n\n".join(parts)


def _early_section(held_out: Sequence[EarlyClass]) -> str:
    parts = ["## How early does it work? (held-out class)"]
    for c in held_out:
        rows = []
        for cutoff, e in sorted(c.experiments.items()):
            by_name = {m.name: m for m in e.methods}
            model, base = by_name[MODEL], by_name[BASELINE]
            rows.append(
                [
                    f"end of week {cutoff}",
                    f"{e.scored} / {e.positives}",
                    fixed(model.auc, 2),
                    fixed(base.auc, 2),
                    fixed(model.precision, 2),
                    fixed(base.precision, 2),
                ]
            )
        header = [
            "cutoff",
            "scored / at risk",
            "model AUC",
            "first-try AUC",
            f"model precision, top {TOP_K}",
            f"first-try precision, top {TOP_K}",
        ]
        parts.append(f"Seed {c.seed}\n\n" + _table(header, rows))
    parts.append(
        "The label changes with the cutoff (it only looks at problems first tried after it), so "
        "rows are not the same question; each row is fitted on the training class at that cutoff."
    )
    return "\n\n".join(parts)


def _weights_section(model: LogisticModel) -> str:
    ordered = sorted(
        zip(FEATURE_NAMES, model.weights, strict=True), key=lambda p: (-abs(p[1]), p[0])
    )
    rows = [[f"`{name}`", fixed(weight, 2), _direction(weight)] for name, weight in ordered]
    return (
        f"## What the model learned (end of week {MAIN_CUTOFF})\n\n"
        + _table(["input", "weight (per standard deviation)", "a higher value means"], rows)
        + "\n\nWeights of correlated inputs (first-try share and Rasch skill measure nearly the "
        "same thing) can trade off against each other, so read the signs loosely, not the sizes."
    )


def _direction(weight: float) -> str:
    if abs(weight) < 0.005:
        return "no effect"
    return "more at risk" if weight > 0 else "less at risk"


def _stopped_section(classes: Sequence[EarlyClass]) -> str:
    rows = [[str(c.seed), str(c.stopped), f"{c.stopped_flagged} of {TOP_K}"] for c in classes]
    return (
        "## Students who stopped coming\n\n"
        + _table(
            ["seed", "stopped before the last week", f"of them in the model's top {TOP_K}"], rows
        )
        + "\n\nThe label is about *how well* a student does later, not whether they come back. "
        "In the simulator a student who will quit behaves like an average student until the week "
        'they stop, so no model can see it coming; "no submission for a week" catches them only '
        "after the fact. This report does not claim to predict dropping out."
    )


def _reading_section(held_out: Sequence[EarlyClass]) -> str:
    lines = ["## Reading the numbers"]
    for c in held_out:
        e = c.experiments[MAIN_CUTOFF]
        by_name = {m.name: m for m in e.methods}
        model, base = by_name[MODEL], by_name[BASELINE]
        inside = base.low <= model.auc <= base.high
        verdict = (
            "the difference is inside the first-try rule's interval: no proof the model is "
            "better than the simple rule"
            if inside
            else "the model's AUC is outside the first-try rule's interval"
        )
        lines.append(
            f"- Seed {c.seed}, end of week {MAIN_CUTOFF}: model AUC {fixed(model.auc, 2)} vs "
            f"first-try rule {fixed(base.auc, 2)} (chance 0.50); {verdict}. Top {TOP_K}: "
            f"{fixed(model.precision * TOP_K, 0)} of {TOP_K} flagged students are really at "
            f"risk, against {fixed(base.precision * TOP_K, 0)} for the first-try rule."
        )
    return "\n".join(lines)


def _limits_section(classes: Sequence[EarlyClass], held_out: Sequence[EarlyClass]) -> str:
    positives = ", ".join(
        f"{c.experiments[MAIN_CUTOFF].positives} at risk in seed {c.seed}" for c in held_out
    )
    worse = [
        f"end of week {cutoff} (seed {c.seed})"
        for c in held_out
        for cutoff, e in sorted(c.experiments.items())
        if _auc(e, MODEL) < _auc(e, BASELINE) - 0.01
    ]
    early = (
        f"- The model is more than 0.01 AUC worse than the simple first-try rule at: "
        f"{', '.join(worse)}. With {len(FEATURE_NAMES)} inputs and about a dozen at-risk "
        "students it can fit noise.\n"
        if worse
        else ""
    )
    return f"""## Limits

- The classes are simulated. Success is drawn from a student's skill, so a rule that looks at
  past success is *expected* to work well. Nothing here says it would work on real students.
- Few at-risk students ({positives}) and {classes[0].students} students: the intervals are
  wide and one student moves precision by 10 points.
{early}- A high score is a reason for a teacher to check in, never a verdict. The simulator's
  learners never change after a warning; a real warning changes the future it predicts."""


def _auc(experiment: Experiment, name: str) -> float:
    return next(m.auc for m in experiment.methods if m.name == name)


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)
