"""The integrity report: thresholds chosen on seed 0, measured on held-out seed 1 (Week 5 Step 2c).

Deterministic: the same databases and cohort files always give byte-identical text (sorted
rows, fixed number formats, a fixed bootstrap seed, no "generated at" time). It refuses to
render when the code's default thresholds are not the seed-0 winner, so the frozen values in
`signals.IntegrityConfig` can't drift away from the report silently.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from codetutor.evals.report import fixed
from codetutor.integrity.evaluate import (
    BETA,
    GRID_CHARS_PER_S,
    GRID_PASTE_SHARE,
    GRID_SIMILARITY,
    ROUNDS,
    FastFlags,
    GridPoint,
    Interval,
    Labelled,
    caught_by_case,
    false_flag_signals,
    review_ids,
    score,
    search,
    signal_ids,
    student_intervals,
    student_view,
)
from codetutor.integrity.signals import INTEGRITY_VERSION, FlagKind, IntegrityConfig

TOP_SETTINGS = 10


class ThresholdsNotFrozenError(RuntimeError):
    """The code's default thresholds are not the setting the seed-0 search picks."""


@dataclass(frozen=True)
class ClassData:
    """One simulated class: where it came from, its labelled submissions, its flags."""

    seed: int
    database: str
    cohort_file: str  # repo-relative path
    cohort_sha256: str
    rows: list[Labelled]
    fast: FastFlags


def render_report(tuning: ClassData, held_out: ClassData) -> str:
    """The whole report as Markdown. Raises ThresholdsNotFrozenError (see the module doc)."""
    points = search(tuning.fast, tuning.rows)
    config = IntegrityConfig()
    if points[0].config != config:
        raise ThresholdsNotFrozenError(
            f"the seed-{tuning.seed} search picks {_setting(points[0].config)}, but the code's "
            f"defaults are {_setting(config)}: freeze the winner in signals.IntegrityConfig "
            "and bump INTEGRITY_VERSION"
        )
    sections = [
        _intro(tuning, held_out, config),
        _setup_section(tuning, held_out),
        _search_section(tuning, points),
        _held_out_section(tuning, held_out, config, points),
        _students_section(tuning, held_out, config),
        _cases_section(held_out, config),
        _limits(held_out),
    ]
    return "\n\n".join(sections) + "\n"


def _intro(tuning: ClassData, held_out: ClassData, config: IntegrityConfig) -> str:
    return "\n".join(
        [
            "# Integrity checks: chosen on one class, measured on another",
            "",
            f"Detector version **{INTEGRITY_VERSION}**: thresholds {_setting(config)}, chosen "
            f"on simulated class seed {tuning.seed} and measured once on held-out class seed "
            f"{held_out.seed}. A submission **needs review** when it has a signal of how the "
            "code got in (`paste`, `fast_typing`) **and** one of what it is "
            "(`same_as_student`, `same_as_ai`). Flags are for a teacher, never a punishment. "
            "Generated by `scripts/integrity.py report` (docs/integrity.md §2.4).",
        ]
    )


def _setup_section(tuning: ClassData, held_out: ClassData) -> str:
    rows = []
    for data, role in ((tuning, "choose the thresholds"), (held_out, "held out: report")):
        cheating = [r for r in data.rows if r.label.cheating]
        students = {r.submission.student for r in data.rows}
        cheaters = {r.submission.student for r in cheating}
        rows.append(
            [
                f"seed {data.seed}",
                role,
                f"`{data.database}`",
                str(len(data.rows)),
                f"{len(cheating)} ({_pct(len(cheating), len(data.rows))})",
                f"{len(students)} ({len(cheaters)} cheat)",
                f"`{data.cohort_file}` (sha256 {data.cohort_sha256[:12]})",
            ]
        )
    header = ["Class", "Role", "Database", "Submissions", "Cheating", "Students", "Labels"]
    return "## 1. The two classes\n\n" + _table(header, rows)


def _search_section(tuning: ClassData, points: Sequence[GridPoint]) -> str:
    best = points[0].scores.f
    tied = [p for p in points if p.scores.f == best]
    top = min(TOP_SETTINGS, len(points))
    rows = [
        [
            str(rank),
            fixed(p.config.paste_share, 1),
            fixed(p.config.chars_per_s, 0),
            fixed(p.config.similarity, 1),
            str(p.scores.flagged),
            _num(p.scores.precision),
            _num(p.scores.recall),
            fixed(p.scores.f, 3) + (" ← chosen" if rank == 1 else ""),
        ]
        for rank, p in enumerate(points[:TOP_SETTINGS], start=1)
    ]
    header = ["#", "Paste share", "Chars/s", "Similarity", "Flagged", "P", "R", "F0.5"]
    lines = [
        f"## 2. Choosing the thresholds (seed {tuning.seed} only)",
        "",
        f"{len(points)} settings: paste share {_values(GRID_PASTE_SHARE)} × typing speed "
        f"{_values(GRID_CHARS_PER_S)} characters per second × similarity "
        f'{_values(GRID_SIMILARITY)}. Each is scored by F{fixed(BETA, 1)} of "needs review" '
        "(precision counts more than recall: a false flag costs an honest student's time). "
        "Ties go to the stricter setting: fewer flagged, then higher thresholds.",
        "",
        _table(header, rows),
        "",
        f"F0.5 ranges from {fixed(points[-1].scores.f, 3)} to {fixed(best, 3)} over the "
        f"grid; the top {top} settings are within {fixed(best - points[top - 1].scores.f, 3)} "
        f"of each other, and {len(tied)} tie at the top. Near the top, moving a threshold "
        "trades a few flags: what holds precision down is the evidence itself (§5), not the "
        "thresholds.",
    ]
    return "\n".join(lines)


def _held_out_section(
    tuning: ClassData, held_out: ClassData, config: IntegrityConfig, points: Sequence[GridPoint]
) -> str:
    tuning_flags = tuning.fast.flags(config)
    held_flags = held_out.fast.flags(config)
    signals: list[tuple[str, set[int], set[int]]] = [
        ("**needs review**", review_ids(tuning_flags), review_ids(held_flags))
    ]
    for kind in FlagKind:
        signals.append(
            (f"`{kind.value}` alone", signal_ids(tuning_flags, kind), signal_ids(held_flags, kind))
        )
    rows = []
    undefined = 0
    for name, tuning_ids, held_ids in signals:
        before = score(tuning_ids, tuning.rows)
        after = score(held_ids, held_out.rows)
        precision_ci, recall_ci = student_intervals(held_ids, held_out.rows)
        undefined = max(undefined, *(ci.undefined for ci in (precision_ci, recall_ci) if ci))
        rows.append(
            [
                name,
                f"{_num(before.precision)} / {_num(before.recall)}",
                str(after.flagged),
                f"{_num(after.precision)} {_ci(precision_ci)}",
                f"{_num(after.recall)} {_ci(recall_ci)}",
                fixed(after.f, 3),
            ]
        )
    header = [
        "Signal",
        f"seed {tuning.seed} P / R (tuning)",
        f"seed {held_out.seed} flagged",
        "Precision [95%]",
        "Recall [95%]",
        "F0.5",
    ]
    tied = [p.config for p in points if p.scores.f == points[0].scores.f and p.config != config]
    lines = [
        f"## 3. The held-out result (seed {held_out.seed})",
        "",
        f"Intervals resample the **students** ({ROUNDS} times, seed 0), not the submissions: "
        "one student's submissions are not independent (a copier makes many similar ones). "
        "Resamples without a value (nothing flagged or no cheating drawn): "
        f"{'none' if undefined == 0 else f'at most {undefined}'}.",
        "",
        _table(header, rows),
    ]
    if tied:
        lines += [
            "",
            f"The settings that tied on seed {tuning.seed}, on seed {held_out.seed} (looked at "
            "only after freezing; not used to choose):",
            "",
            _table(
                ["Setting", "Flagged", "P", "R", "F0.5"],
                [
                    [_setting(c), str(s.flagged), _num(s.precision), _num(s.recall), fixed(s.f, 3)]
                    for c in tied
                    for s in [score(review_ids(held_out.fast.flags(c)), held_out.rows)]
                ],
            ),
        ]
    return "\n".join(lines)


def _students_section(tuning: ClassData, held_out: ClassData, config: IntegrityConfig) -> str:
    rows = []
    for data in (tuning, held_out):
        view = student_view(review_ids(data.fast.flags(config)), data.rows)
        rows.append(
            [
                f"seed {data.seed}",
                f"{view.cheating_students_flagged} of {view.cheating_students}",
                f"{view.honest_students_flagged} of {view.honest_students}",
            ]
        )
    header = [
        "Class",
        "Students who cheated: ≥ 1 submission to review",
        "Honest students: ≥ 1 false flag",
    ]
    return "\n".join(
        [
            "## 4. Per student",
            "",
            'A teacher looks at students, not rows. "Honest" = never cheated in the '
            "simulation; a cheater's honest submissions can be flagged too (not counted here).",
            "",
            _table(header, rows),
        ]
    )


def _cases_section(held_out: ClassData, config: IntegrityConfig) -> str:
    flags = held_out.fast.flags(config)
    flagged = review_ids(flags)
    cases = caught_by_case(flagged, held_out.rows)
    cheating = [[c, f"{hit} of {total}", _pct(hit, total)] for c, (hit, total) in cases.items()]
    combos = false_flag_signals(flags, held_out.rows)
    false_rows = [[f"`{combo}`", str(count)] for combo, count in combos.items()]
    false_total = sum(combos.values())
    ide_hits = cases.get("honest, ide_paste", (0, 0))[0]
    return "\n".join(
        [
            f"## 5. Where it works and where it fails (seed {held_out.seed})",
            "",
            "How each kind of submission was made (the label: source, disguise, entry) and how "
            "many need review. For honest rows every flag is a false flag.",
            "",
            _table(["Case", "Need review", "Share"], cheating),
            "",
            f"{ide_hits} of the {false_total} false flags are honest IDE pastes: a whole program "
            "pasted from the student's own editor whose structure other students (or a known AI "
            "answer) also have. Which signals fired on the honest submissions that need review:",
            "",
            _table(["Signals", "Honest submissions"], false_rows or [["(none)", "0"]]),
        ]
    )


def _limits(held_out: ClassData) -> str:
    students = {r.submission.student for r in held_out.rows}
    cheaters = {r.submission.student for r in held_out.rows if r.label.cheating}
    return LIMITS.format(cheaters=len(cheaters), students=len(students), seed=held_out.seed)


LIMITS = """## 6. What these numbers can and cannot say

- **The simulator chose the cheaters.** Their pasting, retyping speed (60-120 ms per
  character, little thinking time) and disguises are our choices (docs/integrity.md §1.6).
  `fast_typing` works here because we made retypers fast; real ones can type slowly.
- **Few cheaters.** {cheaters} of {students} students cheat in seed {seed}, so the
  intervals are wide and one student more or less moves recall a lot. The intervals are
  about which *students* we had; they say nothing about a different kind of cheater.
- **Honest look-alikes may be too common, or too rare.** Honest code comes from a small pool
  (bank solutions and a 1.5B model's answers, renamed), so honest students match each other
  more than a real class might; real beginners write messier code.
- **Chosen once, measured once.** The thresholds were picked on seed 0 before seed 1 was
  scored; changing them after reading this report would turn seed 1 into tuning data."""


def _setting(config: IntegrityConfig) -> str:
    return (
        f"paste {fixed(config.paste_share, 1)} / {fixed(config.chars_per_s, 0)} chars/s / "
        f"similarity {fixed(config.similarity, 1)}"
    )


def _values(values: Sequence[float]) -> str:
    return "{" + ", ".join(f"{v:g}" for v in values) + "}"


def _num(value: float | None) -> str:
    return "–" if value is None else fixed(value, 2)


def _ci(interval: Interval | None) -> str:
    return "–" if interval is None else f"[{fixed(interval.low, 2)}, {fixed(interval.high, 2)}]"


def _pct(part: int, whole: int) -> str:
    return "–" if whole == 0 else fixed(100 * part / whole, 0) + "%"


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)
