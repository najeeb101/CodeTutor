"""The skill report: difficulty and skill estimates against the simulated truth (Week 5 Step 3).

Deterministic: the same databases and cohort files give byte-identical text (sorted rows, fixed
number formats, fixed seeds, no "generated at" time). Nothing is tuned on either class (Rasch's
one setting, the prior spread, is fixed by convention), so both are reported the same way.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from statistics import mean

from codetutor.evals.report import fixed
from codetutor.skill.evaluate import (
    DROP_RANDOM,
    DROP_SKIP,
    REPEATS,
    ROUNDS,
    Agreement,
    bootstrap_pearson,
    compare,
    declared_vs_estimated,
    estimate,
    missing_data_experiment,
)
from codetutor.skill.rasch import PRIOR_SD, Response

LEVELS = ("easy", "medium", "hard")
TOP_DISAGREEMENTS = 5


@dataclass(frozen=True)
class ClassData:
    """One simulated class: its first-attempt responses and the truth to compare with."""

    seed: int
    database: str
    cohort_file: str
    cohort_sha256: str
    submissions: int
    responses: list[Response]  # every graded first attempt
    clean: list[Response]  # the same without first tries the integrity checks flag
    ungraded: int
    excluded: int
    true_skill: Mapping[str, float]
    true_difficulty: Mapping[str, float]
    declared: Mapping[str, str]  # problem id -> easy / medium / hard


def render_report(classes: Sequence[ClassData]) -> str:
    """The whole report as Markdown."""
    sections = [
        _intro(),
        _classes_section(classes),
        _accuracy_section(classes),
        _missing_section(classes),
        _declared_section(classes),
        LIMITS,
    ]
    return "\n\n".join(sections) + "\n"


def _intro() -> str:
    return (
        "# Problem difficulty and student skill from first attempts\n\n"
        "Two estimators on the same data: plain **pass rates** (a problem's difficulty is how "
        "often it fails; a student's skill is the share of problems solved) and a **Rasch** "
        "model (the chance of a first-try solve is `sigmoid(skill - difficulty)`, one number "
        "per student and per problem, fitted together; fixed prior spread "
        f"{fixed(PRIOR_SD, 1)}, nothing tuned). Both see only the database's view; the "
        "simulation's true skills and difficulties are used only to score them. "
        "Generated by `scripts/skill.py report` (docs/integrity.md §3)."
    )


def _classes_section(classes: Sequence[ClassData]) -> str:
    rows = []
    for c in classes:
        rows.append(
            [
                f"seed {c.seed}",
                f"`{c.database}`",
                str(c.submissions),
                str(len(c.responses)),
                str(len(c.clean)),
                f"{c.excluded} flagged, {c.ungraded} ungraded",
                f"`{c.cohort_file}` (sha256 {c.cohort_sha256[:12]})",
            ]
        )
    header = [
        "Class",
        "Database",
        "Submissions",
        "First tries",
        "Without flagged",
        "Left out",
        "Truth",
    ]
    return "## 1. The data\n\n" + _table(header, rows)


def _accuracy_section(classes: Sequence[ClassData]) -> str:
    rows = []
    for c in classes:
        for name, responses in (("all first tries", c.responses), ("without flagged", c.clean)):
            e = estimate(responses)
            for what, units, pairs in (
                (
                    "difficulty",
                    "problems",
                    (
                        ("pass rate", e.rate_difficulty),
                        ("Rasch", e.rasch_difficulty),
                    ),
                ),
                (
                    "skill",
                    "students",
                    (("share solved", e.rate_skill), ("Rasch", e.rasch_skill)),
                ),
            ):
                truth = c.true_difficulty if units == "problems" else c.true_skill
                for method, values in pairs:
                    agree = compare(values, truth)
                    low, high = bootstrap_pearson(values, truth, rounds=ROUNDS)
                    rows.append(
                        [
                            f"seed {c.seed}",
                            name,
                            f"{what} ({agree.n} {units})",
                            method,
                            f"{fixed(agree.pearson, 2)} [{fixed(low, 2)}, {fixed(high, 2)}]",
                            fixed(agree.spearman, 2),
                            _rmse(method, agree),
                        ]
                    )
    header = ["Class", "Data", "Estimating", "Method", "Pearson r [95%]", "Spearman", "RMSE"]
    return (
        "## 2. How close are the estimates to the truth?\n\n"
        f"Intervals resample the units being estimated (problems or students, {ROUNDS} times); "
        "they do not include each estimate's own noise. RMSE is in logits after centring both "
        'sides, only for Rasch (pass rates are on another scale). "Without flagged" drops the '
        "first tries the integrity checks say need review (detector version 1).\n\n"
        + _table(header, rows)
    )


def _missing_section(classes: Sequence[ClassData]) -> str:
    rows = []
    gains = []
    for c in classes:
        for how, text in (
            ("random", f"{round(DROP_RANDOM * 100)}% deleted at random"),
            ("skip", f"students skip problems that are too hard (up to {round(DROP_SKIP * 100)}%)"),
        ):
            r = missing_data_experiment(c.responses, c.true_skill, c.true_difficulty, how)
            gains += [r.rasch_difficulty - r.rate_difficulty, r.rasch_skill - r.rate_skill]
            rows.append(
                [
                    f"seed {c.seed}",
                    text,
                    _pct(r.kept),
                    f"{fixed(r.rate_difficulty, 2)} / {fixed(r.rasch_difficulty, 2)}",
                    f"{fixed(r.rate_skill, 2)} / {fixed(r.rasch_skill, 2)}",
                ]
            )
    header = [
        "Class",
        "Responses deleted",
        "Left",
        "Difficulty r: pass rate / Rasch",
        "Skill r: share / Rasch",
    ]
    return (
        "## 3. When data is missing\n\n"
        f"Mean Pearson r over {REPEATS} seeded deletions. Pass rates can mislead when the "
        "missing answers are not random (a problem the weak students skipped looks easier than "
        "it is); Rasch compares like with like. Measured here: Rasch is ahead in "
        f"{sum(g > 0 for g in gains)} of {len(gains)} comparisons, by {fixed(min(gains), 2)} to "
        f"{fixed(max(gains), 2)} correlation points. A real but small gain on this data.\n\n"
        + _table(header, rows)
    )


def _declared_section(classes: Sequence[ClassData]) -> str:
    parts = [
        "## 4. Declared difficulty against the estimate\n\n"
        "Each problem has a declared level (easy / medium / hard). Mean Rasch difficulty per "
        "level, and the problems whose estimate is furthest from their level's average: "
        "candidates for a teacher to re-label or re-read."
    ]
    for c in classes:
        e = estimate(c.responses)
        checks = declared_vs_estimated(e.rasch_difficulty, c.declared)
        level_rows = []
        for level in LEVELS:
            values = [x.estimated for x in checks if x.declared == level]
            if values:
                level_rows.append([level, str(len(values)), fixed(mean(values), 2)])
        top = [
            [
                f"`{x.problem}`",
                x.declared,
                fixed(x.estimated, 2),
                fixed(x.gap, 2),
                fixed(c.true_difficulty[x.problem], 2),
            ]
            for x in checks[:TOP_DISAGREEMENTS]
        ]
        parts.append(
            f"**Seed {c.seed}**\n\n"
            + _table(["Declared", "Problems", "Mean Rasch difficulty"], level_rows)
        )
        parts.append(
            _table(
                ["Problem", "Declared", "Rasch difficulty", "Gap to level mean", "True difficulty"],
                top,
            )
        )
    return "\n\n".join(parts)


LIMITS = """## 5. What these numbers can and cannot say

- **The simulator follows Rasch.** A student solves with chance `sigmoid(skill - difficulty)`
  (docs/integrity.md §1.1), so this checks that our fitting code recovers the numbers a
  Rasch-shaped world makes. It does not show that real students follow Rasch.
- **Complete data flatters the baselines.** Almost every simulated student tried almost every
  problem, so pass rates do nearly as well as Rasch in §2. §3 is the fairer test.
- **First try is a choice.** Later tries are practice, so they are left out. A student who
  fixes the bug on try 2 counts as "not solved" here.
- **Cheating rows bend the skill estimate.** A pasted answer makes a student look more able.
  Dropping the rows the integrity checks flag helps the skill estimates (§2). For difficulty
  it changes little, because the flagged set also holds honest students and removes data. The
  checks themselves are imperfect (docs/integrity.md §2.4).
- **Estimates, not grades.** Skill numbers are for teachers to see who needs help, never to
  mark a student."""


def _rmse(method: str, agree: Agreement) -> str:
    return fixed(agree.rmse, 2) if method == "Rasch" else "–"


def _pct(share: float) -> str:
    return fixed(100 * share, 0) + "%"


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)
