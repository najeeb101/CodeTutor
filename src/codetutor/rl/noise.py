"""How big is eval luck? (Week 7 Step 1)

The same model, evaluated twice with two different sampling draws (`seed_base` 0 and 1000),
gives two slightly different pass@1 per problem. The spread of those per-problem differences is
the noise a before -> after comparison has before the training does anything.

The rule was written before the runs: a fold's held-out change counts as "above noise" only if
it is larger than `noise_half_width` (a 95% band for the mean of m per-problem differences),
in both sampling draws. Deterministic like the other reports: same files, same bytes.
"""

from __future__ import annotations

from collections.abc import Sequence
from math import sqrt
from statistics import mean, stdev

from codetutor.evals.report import fixed
from codetutor.problems import Problem
from codetutor.rl.after import FoldRun, _signed, held_out_changes, pass_rates
from codetutor.rl.baseline import NamedRun, _records, _table

Z_95 = 1.96


def reeval_differences(first: NamedRun, second: NamedRun) -> dict[str, float]:
    """Per problem: pass@1 of the second evaluation minus the first (same model both times)."""
    ids = {r.problem_id for r in first.data.records} & {r.problem_id for r in second.data.records}
    a = pass_rates(_records(first, ids))
    b = pass_rates(_records(second, ids))
    return {pid: b[pid] - a[pid] for pid in sorted(set(a) & set(b))}


def spread(diffs: Sequence[float]) -> float | None:
    """Standard deviation of per-problem differences (None with fewer than 2 problems)."""
    return stdev(diffs) if len(diffs) > 1 else None


def noise_half_width(sd: float, problems: int) -> float:
    """95% band for the mean of `problems` differences that each have spread `sd`."""
    return Z_95 * sd / sqrt(problems)


def _fmt(value: float | None) -> str:
    return "–" if value is None else fixed(value, 3)


def _same_model_row(label: str, first: NamedRun, second: NamedRun) -> list[str]:
    diffs = reeval_differences(first, second)
    ids = set(diffs)
    p1 = mean(pass_rates(_records(first, ids)).values())
    p2 = mean(pass_rates(_records(second, ids)).values())
    values = list(diffs.values())
    return [
        label,
        str(len(values)),
        fixed(p1, 3),
        fixed(p2, 3),
        _signed(mean(values) if values else None),
        _fmt(spread(values)),
    ]


def render_noise_report(
    baseline: tuple[NamedRun, NamedRun],
    adapters: dict[str, tuple[NamedRun, NamedRun]],
    fold_runs: dict[str, tuple[FoldRun, FoldRun]],
    bank: Sequence[Problem],
) -> str:
    """The noise report.

    `baseline` = (draw 0, draw 1000) of the untrained model; `adapters` = the same pair for
    each adapter; `fold_runs` = per fold, the (draw 0, draw 1000) before/after pairs.
    """
    sd = spread(list(reeval_differences(*baseline).values()))
    rows = [_same_model_row("untrained 0.5B", *baseline)]
    rows += [_same_model_row(f"adapter {name}", *pair) for name, pair in adapters.items()]
    parts = [
        "# Eval noise: the same model, two sampling draws\n",
        "Each model was evaluated twice on all 33 problems (10 answers each, temperature 0.8, "
        "Docker). The draws differ only in `seed_base` (0 and 1000). Nothing else changed, so "
        "every difference below is luck of the sampling. Generated by "
        "`scripts/rl_after.py noise`.\n",
        "## 1. The same model twice\n",
        _table(
            [
                "Model",
                "Problems",
                "pass@1 draw 0",
                "pass@1 draw 1000",
                "Mean difference",
                "SD of differences",
            ],
            rows,
        ),
        "\nThe spread (SD) of the per-problem differences is the noise of one problem's "
        "pass@1 change. A before -> after change has this noise before any training.\n",
    ]
    parts.append(_fold_section(sd, fold_runs, bank))
    parts.append(_limits())
    return "\n".join(parts)


def _fold_section(
    sd: float | None, fold_runs: dict[str, tuple[FoldRun, FoldRun]], bank: Sequence[Problem]
) -> str:
    lines = [
        "## 2. Is the fold's held-out change above the noise?\n",
        "Rule (written before the runs): the change counts as above noise only if its size is "
        "larger than the 95% band `1.96 x SD / sqrt(m)` (SD from the untrained model's two draws, "
        "m = held-out problems), in both draws.\n",
    ]
    if sd is None:
        return "\n".join(lines + ["No SD: fewer than 2 problems."])
    rows = []
    for name, (draw0, draw1) in fold_runs.items():
        changes = [held_out_changes(run, bank) for run in (draw0, draw1)]
        m = len(changes[0])
        band = noise_half_width(sd, m)
        deltas = [mean(a - b for b, a in c.values()) for c in changes]
        verdict = "above noise" if all(abs(d) > band for d in deltas) else "within noise"
        rows.append(
            [name, str(m), _signed(deltas[0]), _signed(deltas[1]), f"±{fixed(band, 3)}", verdict]
        )
    lines.append(
        _table(
            [
                "Fold",
                "Held-out problems",
                "Change draw 0",
                "Change draw 1000",
                "Noise band",
                "Verdict",
            ],
            rows,
        )
    )
    lines.append(f"\nSD used: {fixed(sd, 3)} (per-problem pass@1 difference, one fold's size m).\n")
    return "\n".join(lines)


def _limits() -> str:
    return (
        "## 3. Limits\n\n"
        "- Two draws is the minimum: the SD is itself uncertain.\n"
        "- This is evaluation noise only. **Training noise** (another training seed) is still "
        "unmeasured; it can be larger.\n"
        "- The band treats problems as independent and the SD as the same for every problem.\n"
        "- The rule fixes what counts as above noise; it does not prove transfer.\n"
    )
