"""The "before" report: how the untrained models do, per fold, and how much they can teach.

Deterministic: the same results files give byte-identical text (sorted rows, fixed number
formats, a fixed bootstrap seed, no clock). Reuses the Week 2 metrics and rounding.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from codetutor.evals import metrics
from codetutor.evals.metrics import ProblemStats, RunData
from codetutor.evals.records import EvalRecord
from codetutor.evals.report import fixed
from codetutor.problems import Problem
from codetutor.rl.dataset import FOLDS, fold_names, split
from codetutor.rl.reward import group_stats


@dataclass(frozen=True)
class NamedRun:
    """A results file with the name the report uses for it."""

    label: str
    data: RunData


def _records(run: NamedRun, ids: set[str]) -> list[EvalRecord]:
    return sorted(
        (r for r in run.data.records if r.problem_id in ids),
        key=lambda r: (r.problem_id, r.sample_index),
    )


def _numbers(records: list[EvalRecord]) -> dict[str, str]:
    """pass@1 [95%], pass@5, mean rewards and the group signal for one set of answers."""
    stats = metrics.problem_stats(records)
    n = min((p.n for p in stats.values()), default=0)
    interval = metrics.bootstrap_ci(stats, k=1)
    p1 = metrics.pass_at_k_mean(stats, 1)
    p5 = metrics.pass_at_k_mean(stats, 5)
    partial = [r.result.reward for r in records]
    strict = [1.0 if r.passed else 0.0 for r in records]
    flat = group_stats(partial, n).flat_share if n else 0.0
    flat_strict = group_stats(strict, n).flat_share if n else 0.0
    mixed = [pid for pid, p in stats.items() if 0 < p.c < p.n]
    return {
        "problems": str(len(stats)),
        "pass1": _num(p1) + (f" [{_num(interval[0])}, {_num(interval[1])}]" if interval else ""),
        "pass5": _num(p5),
        "reward": _num(metrics.mean_reward(stats)),
        "flat": f"{fixed(100 * flat, 0)}% / {fixed(100 * flat_strict, 0)}%",
        "mixed": f"{len(mixed)} of {len(stats)}",
    }


def _num(value: float | None) -> str:
    return "–" if value is None else fixed(value, 2)


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def render_report(
    runs: Sequence[NamedRun], bank: Sequence[Problem], cross_check: NamedRun | None = None
) -> str:
    """The whole report as Markdown. `cross_check`: an Ollama run of the same model."""
    sections = [
        _intro(),
        _runs_section(runs),
        _overall_section(runs, cross_check),
        _fold_section(runs, bank),
        _learnable_section(runs),
        LIMITS,
    ]
    return "\n\n".join(sections) + "\n"


def _intro() -> str:
    return (
        '# The "before" baseline for RL training\n\n'
        "The untrained models, answering all 33 problems 10 times each (Hugging Face weights, "
        "temperature 0.8, plain sampling, 1024 new tokens at most, graded by the one grader in "
        'Docker). The "after" run of Week 7 uses exactly these settings. Every problem is '
        "held out in exactly one of four module folds (docs/rl.md §2), so one run per model "
        "gives the baseline of all folds. Generated by `scripts/rl_baseline.py report`."
    )


def _runs_section(runs: Sequence[NamedRun]) -> str:
    rows = []
    for run in runs:
        meta = run.data.meta
        details = meta.model_details
        rows.append(
            [
                run.label,
                f"`{meta.config.model}`",
                f"{len(run.data.records)} of {run.data.expected}",
                str(details.get("dtype", "–")),
                f"{meta.git_commit[:7] if meta.git_commit else '–'}"
                f"{' (dirty)' if meta.git_dirty else ''}",
            ]
        )
    header = ["Run", "Model", "Answers", "dtype", "Code at start"]
    return "## 1. The runs\n\n" + _table(header, rows)


def _overall_section(runs: Sequence[NamedRun], cross_check: NamedRun | None) -> str:
    rows = []
    shown = list(runs) + ([cross_check] if cross_check else [])
    for run in shown:
        ids = {r.problem_id for r in run.data.records}
        n = _numbers(_records(run, ids))
        rows.append([run.label, n["problems"], n["pass1"], n["pass5"], n["reward"], n["flat"]])
    header = [
        "Run",
        "Problems",
        "pass@1 [95%]",
        "pass@5",
        "Mean reward",
        "All-equal groups (partial / all-or-nothing)",
    ]
    text = "## 2. All 33 problems\n\n" + _table(header, rows)
    if cross_check:
        text += (
            f"\n\nThe last row ({cross_check.label}) is the Week 2 Ollama run of the same model, "
            "as a cross-check: another runtime, template and sampler, so a few points of "
            "difference are expected. Intervals resample the problems."
        )
    return text


def _fold_section(runs: Sequence[NamedRun], bank: Sequence[Problem]) -> str:
    rows = []
    for fold in fold_names():
        train, held_out = split(bank, fold)
        for run in runs:
            for side, problems in (("held out", held_out), ("train", train)):
                n = _numbers(_records(run, {p.id for p in problems}))
                rows.append(
                    [
                        fold,
                        ", ".join(str(m) for m in FOLDS[fold]),
                        run.label,
                        side,
                        n["problems"],
                        n["pass1"],
                        n["flat"],
                        n["mixed"],
                    ]
                )
    header = [
        "Fold",
        "Held-out modules",
        "Run",
        "Side",
        "Problems",
        "pass@1 [95%]",
        "All-equal groups",
        "Mixed groups",
    ]
    return (
        "## 3. Per fold\n\n"
        '"All-equal groups": the share of problems whose 10 answers all got the same reward '
        '(partial / all-or-nothing): GRPO learns nothing from them. "Mixed groups": problems '
        "with both passing and failing answers. Held-out sides are small (8-9 problems), so "
        "their intervals are wide.\n\n" + _table(header, rows)
    )


def _learnable_section(runs: Sequence[NamedRun]) -> str:
    parts = ["## 4. Problems GRPO can learn from (mixed groups)"]
    for run in runs:
        stats: dict[str, ProblemStats] = metrics.problem_stats(run.data.records)
        mixed = [(pid, p) for pid, p in stats.items() if 0 < p.c < p.n]
        rows = [[f"`{pid}`", f"{p.c} of {p.n}", fixed(p.mean_reward, 2)] for pid, p in mixed]
        body = _table(["Problem", "Accepted", "Mean reward"], rows) if rows else "None."
        parts.append(f"**{run.label}**: {len(mixed)} of {len(stats)} problems\n\n{body}")
    return "\n\n".join(parts)


LIMITS = """## 5. What these numbers can and cannot say

- **One seed per run.** The batch of 10 answers per problem is made with one fixed seed; the
  intervals resample problems, not seeds or answers.
- **Small folds.** 8-9 held-out problems per fold: one problem is a 11-12 point swing in a fold.
- **A different runtime than Week 2.** The Ollama run used its own template and sampler; the
  cross-check row shows how far apart they land.
- **Reward vs accepted.** Partial credit rewards answers that pass some tests; "accepted" needs
  all of them. Both are shown because the choice of reward mode (Step 4) depends on them."""
