"""The pooled-draws report (Week 7 Step 2a): 30 answers per problem instead of 10.

Step 1 showed that one draw of 10 answers per problem is too noisy to read a fold. Here every
model is evaluated in three draws (`seed_base` 0, 1000, 2000) and the draws are pooled: each
problem then has 30 answers.

The rule was written before the runs. A held-out change is "above noise" only if (1) its 95%
interval over problems excludes 0, and (2) its size is larger than the evaluation band
`1.96 x SD / sqrt(m)`. `SD` is the noise of one problem's pooled before -> after difference,
measured on the untrained model: `sqrt(2 x v / draws)`, where `v` is the average variance of a
problem's pass@1 between draws. Training noise (another training seed) is not measured here.
Deterministic like the other reports: same files, same bytes.
"""

from __future__ import annotations

from collections.abc import Sequence
from math import sqrt
from statistics import mean, variance

from codetutor.evals.report import fixed
from codetutor.problems import Problem
from codetutor.rl.after import _signed, paired, pass_rates
from codetutor.rl.baseline import NamedRun, _records, _table
from codetutor.rl.dataset import split
from codetutor.rl.noise import Z_95, noise_half_width


def pooled_rates(draws: Sequence[NamedRun], ids: set[str]) -> dict[str, float]:
    """Per problem: pass@1 over the answers of all draws together."""
    records = [r for run in draws for r in _records(run, ids)]
    return pass_rates(records)


def draw_variance(draws: Sequence[NamedRun], ids: set[str]) -> float:
    """Average over problems of the variance of pass@1 between the draws (needs 2+ draws)."""
    per_draw = [pass_rates(_records(run, ids)) for run in draws]
    common = set.intersection(*(set(rates) for rates in per_draw))
    return mean(variance([rates[pid] for rates in per_draw]) for pid in sorted(common))


def pooled_difference_sd(draw_var: float, draws: int) -> float:
    """SD of one problem's (after - before) pass@1 when each side pools `draws` draws."""
    return sqrt(2 * draw_var / draws)


def _fmt_interval(interval: tuple[float, float] | None) -> str:
    return "–" if interval is None else f"[{_signed(interval[0])}, {_signed(interval[1])}]"


def render_pooled_report(
    baseline: Sequence[NamedRun],
    adapters: dict[str, Sequence[NamedRun]],
    bank: Sequence[Problem],
) -> str:
    """The pooled report. `baseline` and each adapter: the same draws, in the same order."""
    every_id = {p.id for p in bank}
    draw_count = len(baseline)
    sd = pooled_difference_sd(draw_variance(baseline, every_id), draw_count)
    answers = 10 * draw_count
    parts = [
        f"# GRPO with {answers} answers per problem: pooled sampling draws\n",
        f"Every model was evaluated in {draw_count} draws ({draw_count} x 10 answers per "
        "problem, temperature 0.8, Docker); the draws differ only in `seed_base`. The draws "
        f"are pooled, so each problem has {answers} answers. Generated by "
        "`scripts/rl_after.py pooled`.\n",
        _models_section(baseline, adapters, every_id),
        _folds_section(baseline, adapters, bank, sd),
        _limits(draw_count, sd),
    ]
    return "\n".join(parts)


def _models_section(
    baseline: Sequence[NamedRun], adapters: dict[str, Sequence[NamedRun]], ids: set[str]
) -> str:
    rows = []
    for name, draws in {
        "untrained 0.5B": baseline,
        **{f"adapter {n}": d for n, d in adapters.items()},
    }.items():
        per_draw = [mean(pass_rates(_records(run, ids)).values()) for run in draws]
        rows.append(
            [
                name,
                *[fixed(v, 3) for v in per_draw],
                fixed(mean(pooled_rates(draws, ids).values()), 3),
            ]
        )
    header = ["Model", *[f"draw {k}" for k in range(len(baseline))], "pooled pass@1"]
    return "## 1. All 33 problems\n\n" + _table(header, rows) + "\n"


def _folds_section(
    baseline: Sequence[NamedRun],
    adapters: dict[str, Sequence[NamedRun]],
    bank: Sequence[Problem],
    sd: float,
) -> str:
    rows = []
    pooled_before: dict[str, float] = {}
    pooled_after: dict[str, float] = {}
    for name, draws in adapters.items():
        _, held_out = split(bank, name)
        ids = {p.id for p in held_out}
        before = pooled_rates(baseline, ids)
        after = pooled_rates(draws, ids)
        pooled_before.update(before)
        pooled_after.update(after)
        rows.append(_change_row(f"fold {name}", before, after, sd))
    rows.append(_change_row("all folds pooled", pooled_before, pooled_after, sd))
    header = [
        "Held out",
        "Problems",
        "pass@1 before",
        "pass@1 after",
        "Mean change",
        "95% interval",
        "Better / worse / same",
        "Noise band",
        "Verdict",
    ]
    return (
        "## 2. Held-out change, folds and pooled\n\n"
        "Rule (written before the runs): **above noise** only if the interval excludes 0 and "
        "the change is larger than the evaluation band `1.96 x SD / sqrt(m)`; otherwise "
        "**within noise**.\n\n" + _table(header, rows) + "\n"
    )


def _change_row(
    label: str, before: dict[str, float], after: dict[str, float], sd: float
) -> list[str]:
    pair = paired(before, after)
    m = len(pair["ids"])
    band = noise_half_width(sd, m)
    interval = pair["interval"]
    excludes_zero = interval is not None and (interval[0] > 0 or interval[1] < 0)
    above = excludes_zero and abs(pair["mean"]) > band
    return [
        label,
        str(m),
        fixed(mean(before[i] for i in pair["ids"]), 3),
        fixed(mean(after[i] for i in pair["ids"]), 3),
        _signed(pair["mean"]),
        _fmt_interval(interval),
        f"{pair['better']} / {pair['worse']} / {pair['same']}",
        f"±{fixed(band, 3)}",
        "above noise" if above else "within noise",
    ]


def _limits(draw_count: int, sd: float) -> str:
    return (
        "## 3. Limits\n\n"
        f"- SD used: {fixed(sd, 3)} for one problem's before -> after difference "
        f"(`sqrt(2 x v / {draw_count})`, `v` from the untrained model's {draw_count} draws, "
        f"z = {Z_95}). With {draw_count} draws the SD itself is uncertain.\n"
        "- This is evaluation noise only. **Training noise** (another training seed) is still "
        "unmeasured and can be larger: a fold may be 'above noise' here and still be luck of "
        "one training run.\n"
        "- The interval resamples problems; the band treats problems as independent.\n"
        "- Held-out means a different topic, not an unrelated skill (docs/rl.md §2). The rule "
        "fixes what counts as above noise; it does not prove transfer.\n"
    )


def seeds_agree(change_a: float, change_b: float, band: float) -> bool:
    """The Step 2b rule (written before the second run): same direction, and no further apart
    than the evaluation band. A change of exactly 0 is not "the other direction"."""
    return change_a * change_b >= 0 and abs(change_a - change_b) < band


def _seed_row(
    label: str,
    before: dict[str, float],
    first: dict[str, float],
    second: dict[str, float],
    sd: float,
) -> list[str]:
    one, two, gap = paired(before, first), paired(before, second), paired(first, second)
    band = noise_half_width(sd, len(gap["ids"]))
    agree = seeds_agree(one["mean"], two["mean"], band)
    return [
        label,
        str(len(gap["ids"])),
        fixed(mean(before[i] for i in gap["ids"]), 3),
        _signed(one["mean"]),
        _signed(two["mean"]),
        _signed(gap["mean"]),
        _fmt_interval(gap["interval"]),
        f"±{fixed(band, 3)}",
        "seeds agree" if agree else "seeds disagree",
    ]


def render_seed_report(
    fold: str,
    baseline: Sequence[NamedRun],
    seed0: Sequence[NamedRun],
    seed1: Sequence[NamedRun],
    bank: Sequence[Problem],
) -> str:
    """Two training seeds of one fold, each evaluated in the same pooled draws."""
    every_id = {p.id for p in bank}
    draw_count = len(baseline)
    sd = pooled_difference_sd(draw_variance(baseline, every_id), draw_count)
    train, held_out = split(bank, fold)
    rows = []
    for label, problems in (("held out", held_out), ("train", train)):
        ids = {p.id for p in problems}
        rows.append(
            _seed_row(
                f"fold {fold} {label}",
                pooled_rates(baseline, ids),
                pooled_rates(seed0, ids),
                pooled_rates(seed1, ids),
                sd,
            )
        )
    header = [
        "Problems",
        "Count",
        "pass@1 before",
        "Change seed 0",
        "Change seed 1",
        "Seed 1 − seed 0",
        "95% interval",
        "Noise band",
        "Verdict",
    ]
    answers = 10 * draw_count
    return (
        f"# Fold {fold}: two training seeds\n\n"
        f"The same recipe (LoRA, 100 steps x 4 prompts, partial reward) trained twice, with "
        f"`--seed 0` and `--seed 1`. Each adapter was evaluated in {draw_count} sampling "
        f"draws, pooled to {answers} answers per problem, like the untrained model. Generated "
        "by `scripts/rl_after.py seeds`.\n\n"
        "## 1. Do the two seeds agree?\n\n"
        "Rule (written before the second run): the seeds **agree** if both changes point the "
        "same way and the two changes differ by less than the evaluation band "
        "`1.96 x SD / sqrt(m)`; otherwise they **disagree**, and one training run cannot be "
        "trusted on its own.\n\n" + _table(header, rows) + "\n\n"
        "## 2. Limits\n\n"
        f"- SD used: {fixed(sd, 3)} (untrained model, {draw_count} draws). Two seeds are the "
        "minimum: the difference between them is itself one noisy number.\n"
        "- The interval resamples problems only. Agreement of two seeds does not prove "
        "transfer: it only says the result is repeatable. Whether a change is above noise is "
        "decided by `pooled.md`.\n"
        "- Same fold, same training problems, same data order seed rules as Week 6.\n"
    )
